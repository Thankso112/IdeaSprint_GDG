import React, { useEffect, useRef, useState, useCallback } from 'react';
import { 
  X, 
  Camera, 
  Upload, 
  Sparkles, 
  CheckCircle2, 
  AlertCircle, 
  RefreshCw, 
  Zap, 
  ShieldCheck, 
  QrCode,
  FlipHorizontal
} from 'lucide-react';
import jsQR from 'jsqr';
import confetti from 'canvas-confetti';
import { FoodListing } from '../types';

interface PickupQRScannerModalProps {
  isOpen: boolean;
  onClose: () => void;
  // If provided, targets this specific claimed listing; otherwise can validate any claimed listing in list
  targetListing?: FoodListing | null;
  claimedListings: FoodListing[];
  onValidatePickup: (listingId: string, pickupCode: string) => boolean;
}

export const PickupQRScannerModal: React.FC<PickupQRScannerModalProps> = ({
  isOpen,
  onClose,
  targetListing,
  claimedListings,
  onValidatePickup,
}) => {
  const videoRef = useRef<HTMLVideoElement | null>(null);
  const canvasRef = useRef<HTMLCanvasElement | null>(null);
  const fileInputRef = useRef<HTMLInputElement | null>(null);
  const animationFrameRef = useRef<number | null>(null);
  const streamRef = useRef<MediaStream | null>(null);

  const [hasCameraPermission, setHasCameraPermission] = useState<boolean | null>(null);
  const [cameraError, setCameraError] = useState<string | null>(null);
  const [facingMode, setFacingMode] = useState<'environment' | 'user'>('environment');
  const [isScanning, setIsScanning] = useState(false);
  const [scanResult, setScanResult] = useState<{
    success: boolean;
    message: string;
    listingName?: string;
    pickupCode?: string;
  } | null>(null);

  // Sound effect on successful QR scan
  const playBeep = () => {
    try {
      const AudioCtx = window.AudioContext || (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
      if (!AudioCtx) return;
      const ctx = new AudioCtx();
      
      const now = ctx.currentTime;
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(880, now); // A5 note
      osc.frequency.exponentialRampToValueAtTime(1760, now + 0.15); // A6 note

      gain.gain.setValueAtTime(0.15, now);
      gain.gain.exponentialRampToValueAtTime(0.01, now + 0.2);

      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.start(now);
      osc.stop(now + 0.2);
    } catch {
      // Audio playback might be restricted without prior gesture
    }
  };

  // Stop video stream and scanning loop
  const stopScanner = useCallback(() => {
    if (animationFrameRef.current) {
      cancelAnimationFrame(animationFrameRef.current);
      animationFrameRef.current = null;
    }
    if (streamRef.current) {
      streamRef.current.getTracks().forEach((track) => track.stop());
      streamRef.current = null;
    }
    setIsScanning(false);
  }, []);

  // Process raw decoded QR text
  const handleDecodedText = useCallback((data: string) => {
    let extractedListingId = '';
    let extractedCode = '';
    let parsedJson: Record<string, unknown> | null = null;

    try {
      parsedJson = JSON.parse(data);
      if (parsedJson && typeof parsedJson === 'object') {
        extractedListingId = String(parsedJson.listingId || '');
        extractedCode = String(parsedJson.pickupCode || '');
      }
    } catch {
      // Not JSON: check if it's a URL query param or plain text
      if (data.includes('listingId=') || data.includes('code=')) {
        try {
          const url = new URL(data, 'https://foodbridge.local');
          extractedListingId = url.searchParams.get('listingId') || '';
          extractedCode = url.searchParams.get('code') || '';
        } catch {}
      } else if (/^\d{4}$/.test(data.trim())) {
        extractedCode = data.trim();
      }
    }

    // Determine target listing
    let matchedListing: FoodListing | undefined;

    if (targetListing) {
      matchedListing = targetListing;
    } else if (extractedListingId) {
      matchedListing = claimedListings.find((l) => l.id === extractedListingId);
    } else if (extractedCode) {
      matchedListing = claimedListings.find(
        (l) => (l.pickupCode || '4829').trim() === extractedCode.trim()
      );
    }

    if (!matchedListing) {
      setScanResult({
        success: false,
        message: 'No matching claimed pickup found for this QR code. Please verify the QR was generated by the donor.',
      });
      return;
    }

    const effectiveCode = extractedCode || matchedListing.pickupCode || '4829';

    // Validate the pickup
    const success = onValidatePickup(matchedListing.id, effectiveCode);

    if (success) {
      playBeep();
      try {
        confetti({
          particleCount: 100,
          spread: 80,
          origin: { y: 0.6 },
          colors: ['#10b981', '#34d399', '#f59e0b', '#059669'],
        });
      } catch {}

      setScanResult({
        success: true,
        message: 'Pickup code verified successfully! Meal status updated to Picked Up.',
        listingName: matchedListing.foodName,
        pickupCode: effectiveCode,
      });

      stopScanner();

      // Auto close after brief celebration
      setTimeout(() => {
        onClose();
      }, 2200);
    } else {
      setScanResult({
        success: false,
        message: `Validation failed for "${matchedListing.foodName}". Code mismatch or expired listing.`,
      });
    }
  }, [targetListing, claimedListings, onValidatePickup, stopScanner, onClose]);

  // Main video frame analysis loop
  const tick = useCallback(() => {
    if (!videoRef.current || !canvasRef.current) return;
    const video = videoRef.current;
    const canvas = canvasRef.current;

    if (video.readyState === video.HAVE_ENOUGH_DATA) {
      canvas.width = video.videoWidth;
      canvas.height = video.videoHeight;
      const ctx = canvas.getContext('2d');
      if (ctx) {
        ctx.drawImage(video, 0, 0, canvas.width, canvas.height);
        const imageData = ctx.getImageData(0, 0, canvas.width, canvas.height);
        const code = jsQR(imageData.data, imageData.width, imageData.height, {
          inversionAttempts: 'dontInvert',
        });

        if (code && code.data) {
          handleDecodedText(code.data);
          return; // Stop scanning loop on detection
        }
      }
    }

    animationFrameRef.current = requestAnimationFrame(tick);
  }, [handleDecodedText]);

  // Start webcam
  const startCamera = useCallback(async () => {
    stopScanner();
    setCameraError(null);
    setScanResult(null);

    try {
      if (!navigator.mediaDevices || !navigator.mediaDevices.getUserMedia) {
        throw new Error('Camera access API is not supported in this browser.');
      }

      const stream = await navigator.mediaDevices.getUserMedia({
        video: {
          facingMode: facingMode,
          width: { ideal: 1280 },
          height: { ideal: 720 },
        },
      });

      streamRef.current = stream;
      if (videoRef.current) {
        videoRef.current.srcObject = stream;
        videoRef.current.setAttribute('playsinline', 'true');
        await videoRef.current.play();
        setHasCameraPermission(true);
        setIsScanning(true);
        animationFrameRef.current = requestAnimationFrame(tick);
      }
    } catch (err: unknown) {
      const errorMsg = err instanceof Error ? err.message : String(err);
      console.warn('Camera stream error:', errorMsg);
      setHasCameraPermission(false);
      setCameraError(
        'Camera access was denied or not available in this environment. You can upload a photo of the QR code or use the 1-Tap Demo Scan button below.'
      );
    }
  }, [facingMode, stopScanner, tick]);

  useEffect(() => {
    if (isOpen) {
      startCamera();
    } else {
      stopScanner();
      setScanResult(null);
    }

    return () => {
      stopScanner();
    };
  }, [isOpen, startCamera, stopScanner]);

  // File Upload scanning fallback
  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (event) => {
      const img = new Image();
      img.onload = () => {
        const canvas = canvasRef.current || document.createElement('canvas');
        canvas.width = img.width;
        canvas.height = img.height;
        const ctx = canvas.getContext('2d');
        if (ctx) {
          ctx.drawImage(img, 0, 0);
          const imageData = ctx.getImageData(0, 0, img.width, img.height);
          const code = jsQR(imageData.data, imageData.width, imageData.height);
          if (code && code.data) {
            handleDecodedText(code.data);
          } else {
            setScanResult({
              success: false,
              message: 'No QR code detected in this image. Please upload a clear photo of the donor\'s QR code.',
            });
          }
        }
      };
      img.src = event.target?.result as string;
    };
    reader.readAsDataURL(file);
  };

  // 1-Click Instant Demo Simulator
  const handleSimulateDemoScan = () => {
    const target = targetListing || claimedListings[0];
    if (!target) {
      setScanResult({
        success: false,
        message: 'No active claimed listing available to simulate scan.',
      });
      return;
    }

    const payload = JSON.stringify({
      app: 'foodbridge',
      type: 'pickup_verification',
      listingId: target.id,
      pickupCode: target.pickupCode || '4829',
      foodName: target.foodName,
      donorName: target.donorName,
    });

    handleDecodedText(payload);
  };

  const toggleCameraFacing = () => {
    setFacingMode((prev) => (prev === 'environment' ? 'user' : 'environment'));
  };

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-in fade-in duration-200">
      <div 
        className="bg-white rounded-3xl max-w-md w-full shadow-2xl border border-stone-200 overflow-hidden flex flex-col relative"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Header */}
        <div className="p-5 pb-4 bg-gradient-to-r from-stone-900 via-slate-900 to-emerald-950 text-white relative">
          <button
            onClick={() => {
              stopScanner();
              onClose();
            }}
            className="absolute top-4 right-4 p-1.5 rounded-full bg-white/10 hover:bg-white/20 text-white transition"
            aria-label="Close"
          >
            <X className="w-5 h-5" />
          </button>
          <div className="flex items-center gap-2 mb-1">
            <span className="p-1 rounded-lg bg-emerald-500/20 text-emerald-400 border border-emerald-400/30">
              <Camera className="w-4 h-4" />
            </span>
            <span className="text-xs uppercase tracking-wider font-extrabold text-emerald-400">
              Instant Pickup Reader
            </span>
          </div>
          <h3 className="text-xl font-black tracking-tight text-white">
            Scan Donor Pickup QR
          </h3>
          <p className="text-xs text-stone-300 mt-0.5">
            {targetListing
              ? `Scanning for: ${targetListing.foodName} (${targetListing.donorName})`
              : 'Point camera at the QR code displayed on donor\'s screen.'}
          </p>
        </div>

        {/* Viewfinder Area */}
        <div className="relative bg-black flex flex-col items-center justify-center min-h-[300px] overflow-hidden">
          {/* Live Video */}
          <video
            ref={videoRef}
            className="w-full h-[320px] object-cover"
            playsInline
            muted
          />
          {/* Hidden Canvas for QR processing */}
          <canvas ref={canvasRef} className="hidden" />

          {/* Viewfinder Target Box Overlay */}
          {isScanning && !scanResult?.success && (
            <div className="absolute inset-0 pointer-events-none flex items-center justify-center">
              {/* Darkened outer mask */}
              <div className="relative w-64 h-64 rounded-2xl border-2 border-emerald-400/80 shadow-[0_0_0_9999px_rgba(0,0,0,0.45)]">
                {/* 4 Corner Targeting Marks */}
                <div className="absolute -top-1.5 -left-1.5 w-6 h-6 border-t-4 border-l-4 border-emerald-400 rounded-tl-lg"></div>
                <div className="absolute -top-1.5 -right-1.5 w-6 h-6 border-t-4 border-r-4 border-emerald-400 rounded-tr-lg"></div>
                <div className="absolute -bottom-1.5 -left-1.5 w-6 h-6 border-b-4 border-l-4 border-emerald-400 rounded-bl-lg"></div>
                <div className="absolute -bottom-1.5 -right-1.5 w-6 h-6 border-b-4 border-r-4 border-emerald-400 rounded-br-lg"></div>

                {/* Animated Laser Scanning Line */}
                <div className="absolute inset-x-2 h-0.5 bg-gradient-to-r from-transparent via-emerald-400 to-transparent shadow-[0_0_8px_#10b981] animate-bounce"></div>
              </div>

              <div className="absolute bottom-4 bg-black/75 backdrop-blur-md px-3.5 py-1.5 rounded-full border border-white/20 text-white text-xs font-semibold flex items-center gap-2">
                <span className="w-2 h-2 rounded-full bg-emerald-400 animate-ping"></span>
                <span>Align QR code within the frame</span>
              </div>
            </div>
          )}

          {/* Camera Controls Overlay (Flip Camera) */}
          {isScanning && (
            <button
              type="button"
              onClick={toggleCameraFacing}
              className="absolute top-3 right-3 p-2 bg-black/60 hover:bg-black/80 rounded-full text-white border border-white/20 backdrop-blur-xs transition"
              title="Switch front/back camera"
            >
              <FlipHorizontal className="w-4 h-4" />
            </button>
          )}

          {/* Fallback & Camera Permission Error Banner */}
          {cameraError && !scanResult && (
            <div className="absolute inset-0 bg-stone-900/95 p-6 flex flex-col items-center justify-center text-center text-white space-y-3 z-10">
              <div className="w-12 h-12 rounded-2xl bg-amber-500/20 text-amber-400 flex items-center justify-center border border-amber-400/30">
                <AlertCircle className="w-6 h-6" />
              </div>
              <h4 className="font-bold text-sm text-stone-100">Live Camera Unavailable</h4>
              <p className="text-xs text-stone-400 max-w-xs">
                {cameraError}
              </p>
              <div className="flex items-center gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => fileInputRef.current?.click()}
                  className="px-3.5 py-2 rounded-xl bg-white text-stone-900 hover:bg-stone-100 font-bold text-xs flex items-center gap-1.5 shadow-sm transition"
                >
                  <Upload className="w-3.5 h-3.5" />
                  <span>Upload QR Image</span>
                </button>
                <button
                  type="button"
                  onClick={startCamera}
                  className="px-3.5 py-2 rounded-xl border border-stone-600 hover:bg-stone-800 text-stone-200 font-bold text-xs flex items-center gap-1.5 transition"
                >
                  <RefreshCw className="w-3.5 h-3.5" />
                  <span>Retry Camera</span>
                </button>
              </div>
            </div>
          )}

          {/* Success Validation Overlay */}
          {scanResult?.success && (
            <div className="absolute inset-0 bg-emerald-950/95 p-6 flex flex-col items-center justify-center text-center text-white space-y-3 z-20 animate-in zoom-in-95 duration-200">
              <div className="w-16 h-16 rounded-3xl bg-emerald-500 text-white flex items-center justify-center shadow-lg shadow-emerald-500/50">
                <CheckCircle2 className="w-9 h-9" />
              </div>
              <div>
                <h4 className="font-black text-lg text-emerald-200">Pickup Code Verified!</h4>
                <p className="text-xs text-emerald-300 font-mono mt-1">
                  Validated Code: <span className="bg-emerald-800/80 px-2 py-0.5 rounded font-black text-white">{scanResult.pickupCode}</span>
                </p>
              </div>
              <p className="text-xs text-emerald-100 max-w-xs">
                {scanResult.message}
              </p>
            </div>
          )}
        </div>

        {/* Scan Status & Errors */}
        {scanResult && !scanResult.success && (
          <div className="p-3 bg-rose-50 border-t border-rose-200 text-xs text-rose-800 flex items-center gap-2">
            <AlertCircle className="w-4 h-4 text-rose-600 shrink-0" />
            <p className="font-medium flex-1">{scanResult.message}</p>
          </div>
        )}

        {/* Actions & Alternative Inputs */}
        <div className="p-4 bg-white border-t border-stone-200 space-y-2.5">
          <div className="flex items-center justify-between gap-2">
            {/* Hidden File Input */}
            <input
              ref={fileInputRef}
              type="file"
              accept="image/*"
              className="hidden"
              onChange={handleFileUpload}
            />

            <button
              type="button"
              onClick={() => fileInputRef.current?.click()}
              className="flex-1 py-2 px-3 rounded-xl border border-stone-200 hover:bg-stone-50 font-bold text-xs text-stone-700 flex items-center justify-center gap-1.5 transition"
            >
              <Upload className="w-3.5 h-3.5 text-stone-500" />
              <span>Scan from Photo</span>
            </button>

            {/* 1-Tap Demo Scan Simulator */}
            <button
              type="button"
              onClick={handleSimulateDemoScan}
              className="flex-1 py-2 px-3 rounded-xl bg-amber-50 hover:bg-amber-100 border border-amber-300 font-bold text-xs text-amber-900 flex items-center justify-center gap-1.5 transition"
              title="Instantly simulate scanning donor's QR code for testing without a second camera"
            >
              <Zap className="w-3.5 h-3.5 text-amber-600 fill-amber-500" />
              <span>⚡ 1-Tap Test Scan</span>
            </button>
          </div>

          <p className="text-[11px] text-stone-500 text-center font-medium">
            Align camera at the QR code on the donor's screen. The pickup code will be validated and marked completed automatically.
          </p>
        </div>
      </div>
    </div>
  );
};
